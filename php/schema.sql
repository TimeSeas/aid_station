PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS users (
 user_id INTEGER PRIMARY KEY AUTOINCREMENT, openid TEXT UNIQUE, phone TEXT UNIQUE,
 password_hash TEXT, nickname TEXT NOT NULL, avatar TEXT NOT NULL DEFAULT '/images/icon/avatar.png',
 user_type INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(user_id), expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS pets (
 pet_id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, species TEXT NOT NULL,
 gender INTEGER NOT NULL DEFAULT 0, age INTEGER NOT NULL DEFAULT 0, health_status TEXT NOT NULL DEFAULT '',
 description TEXT NOT NULL DEFAULT '', images TEXT NOT NULL DEFAULT '[]',
 is_adopted INTEGER NOT NULL DEFAULT 0, created_by INTEGER NOT NULL REFERENCES users(user_id),
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS posts (
 post_id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(user_id),
 content TEXT NOT NULL, images TEXT NOT NULL DEFAULT '[]', like_count INTEGER NOT NULL DEFAULT 0,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS comments (
 comment_id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(user_id),
 parent_id INTEGER NOT NULL REFERENCES posts(post_id), parent_type TEXT NOT NULL DEFAULT 'post',
 content TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS rescues (
 rescue_id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(user_id),
 name TEXT NOT NULL, location TEXT NOT NULL, images TEXT NOT NULL, status INTEGER NOT NULL DEFAULT 0,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS adoptions (
 application_id INTEGER PRIMARY KEY AUTOINCREMENT, pet_id INTEGER NOT NULL REFERENCES pets(pet_id),
 user_id INTEGER NOT NULL REFERENCES users(user_id), details TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(pet_id,user_id)
);
CREATE TABLE IF NOT EXISTS messages (
 msg_id INTEGER PRIMARY KEY AUTOINCREMENT, sender_id INTEGER NOT NULL REFERENCES users(user_id),
 receiver_id INTEGER NOT NULL REFERENCES users(user_id), content TEXT NOT NULL,
 msg_type INTEGER NOT NULL DEFAULT 1, status INTEGER NOT NULL DEFAULT 0,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS follows (
 follower_id INTEGER NOT NULL REFERENCES users(user_id), followed_id INTEGER NOT NULL REFERENCES users(user_id),
 PRIMARY KEY(follower_id,followed_id)
);
CREATE INDEX IF NOT EXISTS idx_messages_pair ON messages(sender_id,receiver_id,msg_id);
CREATE INDEX IF NOT EXISTS idx_comments_post ON comments(parent_id,comment_id);
CREATE INDEX IF NOT EXISTS idx_pets_owner ON pets(created_by);
